const byId = (id) => document.getElementById(id);

function readPreference(key, fallback) {
  try {
    return window.localStorage.getItem(key) || fallback;
  } catch {
    return fallback;
  }
}

function writePreference(key, value) {
  try {
    window.localStorage.setItem(key, value);
  } catch {
    // Private browsing can reject localStorage; the controls still work for this visit.
  }
}

function translate(key) {
  return translations[state.lang]?.[key] || translations.es[key] || key;
}

function applyLanguage() {
  const dictionary = translations[state.lang];
  document.documentElement.lang = languageMeta[state.lang].locale;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const key = element.dataset.i18nAria;
    if (dictionary[key]) element.setAttribute("aria-label", dictionary[key]);
  });

  const languageSelect = byId("language-select");
  if (languageSelect) languageSelect.value = state.lang;
}

function findEnglishEntry(entry) {
  if (!entry) return null;
  return state.entriesEnglish.find((translated) => translated.id === entry.id) || null;
}

function getTranslatedEntry(entry) {
  return state.lang === "en" ? findEnglishEntry(entry) : null;
}

function getActiveEntry(entry) {
  return getTranslatedEntry(entry) || entry;
}

function getReaderSource(entry) {
  if (entry?.kind === "ficha-de-autor") {
    return {
      titleKey: "authorSourceTitle",
      copyKey: "authorSourceCopy",
      primaryUrl: "https://enciclopedia.banrepcultural.org/Rafael_Pombo",
      primaryKey: "authorSourceLink",
      editionKey: "sourceEditionAuthor",
      statusKey: "sourceStatusAuthor",
      secondaryUrl: "anexo.html",
      secondaryKey: "sourceAnnexLink",
    };
  }

  if (entry?.id === "rinrin-renacuajo") {
    return {
      titleKey: "sourceShortTitle",
      copyKey: "sourceShortCopy",
      primaryUrl: "https://www.cervantesvirtual.com/obra/el-renacuajo-paseador-1168925/",
      primaryKey: "viewRecord",
      editionKey: "sourceEditionRinrin",
      statusKey: "sourceStatusValue",
      secondaryUrl: state.textSource,
      secondaryKey: "openTranscription",
    };
  }

  return {
    titleKey: "sourceAnthologyTitle",
    copyKey: "sourceAnthologyCopy",
    primaryUrl: state.textSource,
    primaryKey: "sourceAnthologyLink",
    editionKey: "sourceEditionPoem",
    statusKey: "sourceStatusValue",
    secondaryUrl: null,
    secondaryKey: null,
  };
}

function renderStory() {
  const container = byId("story-text");
  if (!container) return;
  container.replaceChildren();

  const activeStory = getActiveEntry(state.story);
  const translated = Boolean(getTranslatedEntry(state.story));
  const activeLanguage = translated ? "en" : "es-CO";
  const title = activeStory?.title || state.story?.title || "";
  const isAuthor = activeStory?.kind === "ficha-de-autor";

  const storyTitle = byId("story-title");
  if (storyTitle && title) storyTitle.textContent = title;
  const storyAuthor = byId("story-author-value");
  if (storyAuthor) storyAuthor.textContent = activeStory?.author || state.story?.author || translate("by");
  const storyPeriod = byId("story-period-value");
  if (storyPeriod) storyPeriod.textContent = isAuthor ? translate("authorYears") : translate("storyYear");
  const sourceWork = byId("source-work-value");
  if (sourceWork && title) sourceWork.textContent = title;
  const readerSource = getReaderSource(state.story);
  const sourceTitle = byId("story-source-title");
  if (sourceTitle) sourceTitle.textContent = translate(readerSource.titleKey);
  const sourceCopy = byId("story-source-copy");
  if (sourceCopy) sourceCopy.textContent = translate(readerSource.copyKey);
  const sourceLink = byId("story-source-link");
  if (sourceLink) {
    sourceLink.href = readerSource.primaryUrl;
    sourceLink.textContent = translate(readerSource.primaryKey);
  }
  const sourceEdition = byId("source-edition-value");
  if (sourceEdition) sourceEdition.textContent = translate(readerSource.editionKey);
  const sourceStatus = byId("source-status-value");
  if (sourceStatus) sourceStatus.textContent = translate(readerSource.statusKey);
  const openSourceLink = byId("open-source-link");
  if (openSourceLink) {
    openSourceLink.href = readerSource.primaryUrl;
    openSourceLink.textContent = translate(readerSource.primaryKey);
  }
  const openTranscriptionLink = byId("open-transcription-link");
  if (openTranscriptionLink) {
    openTranscriptionLink.hidden = !readerSource.secondaryUrl;
    if (readerSource.secondaryUrl) openTranscriptionLink.href = readerSource.secondaryUrl;
    if (readerSource.secondaryKey) openTranscriptionLink.textContent = translate(readerSource.secondaryKey);
  }
  container.lang = activeLanguage;
  const contentLabel = isAuthor ? translate("authorTextLabel") : translate("storyTextLabel");
  container.setAttribute("aria-label", `${contentLabel}: ${title}`);

  const note = byId("translation-note-text");
  if (note) {
    note.textContent = state.lang !== "es" && !translated
      ? `${translate("translationUnavailable")} ${translate("translationNote")}`
      : translate("translationNote");
  }

  const badge = byId("translation-badge");
  if (badge) {
    badge.hidden = !translated;
    badge.textContent = state.translationMeta?.label
      ? `${state.translationMeta.label} · ${state.translationMeta.review}`
      : translate("translationBadge");
  }

  const readingParts = Array.isArray(activeStory?.stanzas)
    ? activeStory.stanzas
    : Array.isArray(activeStory?.bio)
      ? activeStory.bio
      : null;

  if (!activeStory || !readingParts) {
    const error = document.createElement("p");
    error.className = "story-stanza";
    error.textContent = translate("storyLoadError");
    container.append(error);
    return;
  }

  readingParts.forEach((stanza) => {
    const paragraph = document.createElement("p");
    paragraph.className = "story-stanza";
    paragraph.textContent = stanza;
    container.append(paragraph);
  });
}

function selectEntry(entry) {
  if (!entry) return;
  stopVoice(translate("voiceReady"));
  state.story = entry;
  renderStory();

  const section = byId("cuento");
  const title = byId("story-title");
  const reduceMotion = document.body.classList.contains("reduce-motion")
    || window.matchMedia?.("(prefers-reduced-motion: reduce)").matches;
  section?.scrollIntoView({ behavior: reduceMotion ? "auto" : "smooth", block: "start" });
  window.setTimeout(() => title?.focus({ preventScroll: true }), reduceMotion ? 0 : 300);
  showToast(`${entry.sculpture}: ${translate("readerLoaded")}`);
}

function renderSculptures() {
  const container = byId("sculpture-list");
  if (!container) return;
  container.setAttribute("aria-busy", "true");
  container.replaceChildren();

  if (!state.entries.length) {
    const message = document.createElement("p");
    message.className = "section-lede";
    message.textContent = translate("storyLoadError");
    container.append(message);
    container.setAttribute("aria-busy", "false");
    return;
  }

  state.entries.forEach((entry, index) => {
    const activeEntry = getActiveEntry(entry);
    const translated = Boolean(getTranslatedEntry(entry));
    const activeLanguage = translated ? "en" : "es-CO";
    const card = document.createElement("article");
    card.className = "sculpture-card" + (entry.kind === "ficha-de-autor" ? " is-author" : "");
    card.lang = activeLanguage;

    const header = document.createElement("div");
    header.className = "sculpture-card-header";

    const number = document.createElement("span");
    number.className = "sculpture-number";
    number.textContent = String(index + 1).padStart(2, "0");
    number.setAttribute("aria-hidden", "true");

    const headingWrap = document.createElement("div");
    const heading = document.createElement("h3");
    heading.textContent = entry.sculpture;
    const work = document.createElement("p");
    work.className = "sculpture-work";
    work.textContent = entry.kind === "ficha-de-autor" ? translate("authorCard") : translate("poemCard") + " · " + activeEntry.title;
    headingWrap.append(heading, work);
    header.append(number, headingWrap);
    card.append(header);

    const readerButton = document.createElement("button");
    readerButton.className = "button button-quiet sculpture-reader-button";
    readerButton.type = "button";
    readerButton.textContent = translate("openReader");
    readerButton.setAttribute("aria-label", `${translate("openReader")}: ${entry.sculpture}`);
    readerButton.addEventListener("click", () => selectEntry(entry));
    card.append(readerButton);

    const details = document.createElement("details");
    const summary = document.createElement("summary");
    summary.textContent = entry.kind === "ficha-de-autor" ? translate("readBio") : translate("readText");
    details.append(summary);

    const translationStatus = document.createElement("p");
    translationStatus.className = "translation-status";
    translationStatus.textContent = translated
      ? translate("translationStatus")
      : state.lang === "es"
        ? translate("sourceLanguageStatus")
        : translate("translationUnavailable");
    details.append(translationStatus);

    if (Array.isArray(activeEntry.bio)) {
      const bio = document.createElement("div");
      bio.className = "sculpture-bio";
      bio.lang = activeLanguage;
      activeEntry.bio.forEach((paragraphText) => {
        const paragraph = document.createElement("p");
        paragraph.textContent = paragraphText;
        bio.append(paragraph);
      });
      details.append(bio);
    } else if (Array.isArray(activeEntry.stanzas)) {
      const story = document.createElement("div");
      story.className = "sculpture-story";
      story.lang = activeLanguage;
      activeEntry.stanzas.forEach((stanza) => {
        const paragraph = document.createElement("p");
        paragraph.className = "sculpture-stanza";
        paragraph.textContent = stanza;
        story.append(paragraph);
      });
      details.append(story);
    }

    const source = document.createElement("span");
    source.className = "sculpture-source";
    source.append(translate("sourceText") + ": ");
    const sourceLink = document.createElement("a");
    sourceLink.href = state.textSource;
    sourceLink.target = "_blank";
    sourceLink.rel = "noopener noreferrer";
    sourceLink.textContent = translate("sourceEditionLink");
    source.append(sourceLink);
    if (activeEntry.sourceNote) {
      source.append(document.createTextNode(" " + activeEntry.sourceNote));
    }
    details.append(source);
    card.append(details);
    container.append(card);
  });
  container.setAttribute("aria-busy", "false");
}

function setBodyPreference(className, storageKey, buttonId) {
  const button = byId(buttonId);
  const enabled = document.body.classList.toggle(className);
  button?.setAttribute("aria-pressed", String(enabled));
  writePreference(storageKey, String(enabled));
}

function restorePreferences() {
  const preferences = [
    ["larger-text", "pombo-larger-text", "larger-text"],
    ["high-contrast", "pombo-high-contrast", "high-contrast"],
    ["reduce-motion", "pombo-reduce-motion", "reduce-motion"],
  ];
  preferences.forEach(([className, storageKey, buttonId]) => {
    const enabled = readPreference(storageKey, "false") === "true";
    document.body.classList.toggle(className, enabled);
    byId(buttonId)?.setAttribute("aria-pressed", String(enabled));
  });
}

function showToast(message) {
  const toast = byId("toast");
  if (!toast) return;
  toast.textContent = message;
  toast.hidden = false;
  window.clearTimeout(showToast.timeout);
  showToast.timeout = window.setTimeout(() => {
    toast.hidden = true;
  }, 2600);
}

function updateVoiceStatus(message) {
  const status = byId("voice-status");
  if (status) status.textContent = message;
}

function stopVoice(message = translate("voiceStopped")) {
  if (window.speechSynthesis) window.speechSynthesis.cancel();
  state.speech = null;
  byId("stop-voice")?.setAttribute("disabled", "disabled");
  updateVoiceStatus(message);
}

function startVoice() {
  if (!("speechSynthesis" in window) || !("SpeechSynthesisUtterance" in window)) {
    updateVoiceStatus(translate("voiceUnsupported"));
    showToast(translate("voiceUnsupported"));
    return;
  }

  const activeStory = getActiveEntry(state.story);
  const readingParts = Array.isArray(activeStory?.stanzas)
    ? activeStory.stanzas
    : Array.isArray(activeStory?.bio)
      ? activeStory.bio
      : [];
  if (!readingParts.length) {
    updateVoiceStatus(translate("storyLoadError"));
    return;
  }

  stopVoice(translate("voiceReady"));
  const translated = Boolean(getTranslatedEntry(state.story));
  const utterance = new SpeechSynthesisUtterance(readingParts.join("\n\n"));
  utterance.lang = translated ? "en-US" : "es-CO";
  utterance.rate = .86;
  utterance.pitch = 1;
  utterance.onend = () => stopVoice(translate("voiceReady"));
  utterance.onerror = () => stopVoice(translate("voiceReady"));
  state.speech = utterance;
  window.speechSynthesis.speak(utterance);
  byId("stop-voice")?.removeAttribute("disabled");
  updateVoiceStatus(translate("voiceStarted"));
}

function setMenu(open) {
  const wasOpen = state.menuOpen;
  state.menuOpen = open;
  const menu = byId("mobile-menu");
  const button = document.querySelector(".menu-button");
  if (menu) menu.hidden = !open;
  button?.setAttribute("aria-expanded", String(open));
  button?.setAttribute("aria-label", open ? translate("closeMenu") : translate("menuLabel"));
  if (open) {
    menu?.querySelector("a")?.focus();
  } else if (wasOpen && menu?.contains(document.activeElement)) {
    button?.focus();
  }
}

async function loadContent() {
  try {
    const response = await fetch("content/sculptures.json", { cache: "no-cache" });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const content = await response.json();
    if (!Array.isArray(content.entries)) throw new Error("No hay entradas de la serie");
    state.entries = content.entries;
    state.textSource = content.textSource || state.textSource;
    state.story = state.entries.find((entry) => entry.id === "rinrin-renacuajo") || state.entries[0] || null;

    try {
      const translationResponse = await fetch("content/sculptures-en.json", { cache: "no-cache" });
      if (!translationResponse.ok) throw new Error(`HTTP ${translationResponse.status}`);
      const translation = await translationResponse.json();
      if (!Array.isArray(translation.entries)) throw new Error("No hay entradas traducidas");
      state.entriesEnglish = translation.entries;
      state.translationMeta = translation.translation || null;
    } catch (translationError) {
      console.warn("Pombo: no se pudo cargar la traducción inglesa", translationError);
      state.entriesEnglish = [];
      state.translationMeta = null;
    }
  } catch (error) {
    console.warn("Pombo: no se pudo cargar la serie", error);
    state.entries = [];
    state.entriesEnglish = [];
    state.translationMeta = null;
    state.story = null;
  }
  renderStory();
  renderSculptures();
}

function bindEvents() {
  byId("language-select")?.addEventListener("change", (event) => {
      state.lang = normalizeLanguage(event.target.value);
      writePreference("pombo-language", state.lang);
      applyLanguage();
      renderStory();
      renderSculptures();
      setMenu(false);
      updateVoiceStatus(translate("voiceReady"));
      showToast(translate("languageChanged"));
  });

  document.querySelector(".menu-button")?.addEventListener("click", () => setMenu(!state.menuOpen));
  document.querySelectorAll(".mobile-menu a").forEach((link) => link.addEventListener("click", () => setMenu(false)));
  byId("device-voice")?.addEventListener("click", startVoice);
  byId("stop-voice")?.addEventListener("click", () => stopVoice());
  byId("larger-text")?.addEventListener("click", () => setBodyPreference("larger-text", "pombo-larger-text", "larger-text"));
  byId("high-contrast")?.addEventListener("click", () => setBodyPreference("high-contrast", "pombo-high-contrast", "high-contrast"));
  byId("reduce-motion")?.addEventListener("click", () => setBodyPreference("reduce-motion", "pombo-reduce-motion", "reduce-motion"));
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && state.menuOpen) setMenu(false);
  });
  window.addEventListener("beforeunload", () => stopVoice(translate("voiceReady")));
}

applyLanguage();
restorePreferences();
bindEvents();
loadContent();

if ("serviceWorker" in navigator && /^(https?:)$/.test(window.location.protocol)) {
  window.addEventListener("load", () => navigator.serviceWorker.register("sw.js").catch(() => undefined));
}
